import gensim
from gensim.models import KeyedVectors
import pymorphy3
import itertools

# Загружаем модель
model = KeyedVectors.load_word2vec_format(
    "cbow.txt",
    binary=False,
    encoding="utf-8"
)

print("Модель загружена")
print("Количество слов:", len(model.key_to_index))

morph = pymorphy3.MorphAnalyzer()


# Проверка, является ли слово существительным
def is_noun(word):
    parsed = morph.parse(word)
    return any(p.tag.POS == "NOUN" for p in parsed)


# Поиск ближайших существительных
def get_nearest_nouns(vector, topn=10):

    results = model.similar_by_vector(vector, topn=500)

    nouns = []

    for word, similarity in results:
        if word.endswith("_NOUN"):
            clean_word = word[:-5]
            nouns.append((clean_word, similarity))

        if len(nouns) == topn:
            break

    return nouns

def main():

    word1 = input("Введите первое слово: ").strip().lower()
    word2 = input("Введите второе слово: ").strip().lower()

    word1_model = word1 + "_NOUN"
    word2_model = word2 + "_NOUN"

    if word1_model not in model.key_to_index:
        print("Первое слово отсутствует среди существительных в модели")
        return

    if word2_model not in model.key_to_index:
        print("Второе слово отсутствует среди существительных в модели")
        return

    vector1 = model[word1_model]
    vector2 = model[word2_model]

    coefficients = range(-50, 51)

    found = False             #логическая переменная, которая показывает, найдено ли подходящее решение. изначально нет
    best_score = float("inf")  #задаём начальное значение лучшего результата как бесконечность. чтобы любое найденное решение оказалось лучше начального
    best_result = None         #переменная для хранения лучшей найденной комбинации коэффициентов и её результатов

    for a, b in itertools.product(coefficients, repeat=2):   #перебираем все возможные пары коэффициентов, itertools.product() создаёт декартово произведение двух наборов коэффициенто

        if a == 0 and b == 0:    #если оба коэффициента равны нулю, результирующий вектор тоже будет нулевым
            continue

        result_vector = a * vector1 + b * vector2

        nearest = get_nearest_nouns(result_vector)  #Передаём результирующий вектор в функцию/ находит десять ближайших к нему слов, оставляя только существительные

        nearest_words = [word for word, similarity in nearest]   #создаём отдельный список, содержащий только слова, без значений косинусного сходства  

        # Позиции исходных слов
        if word1 in nearest_words and word2 in nearest_words: #Проверяем, присутствуют ли оба исходных слова среди десяти ближайших существительных

            found = True #комбинация найжена (попали в первые 10 слов), меняем значение на Истина

            position1 = nearest_words.index(word1) + 1  #Определяем порядковые номера исходных слов в списке ближайших существительных
            position2 = nearest_words.index(word2) + 1

            score = position1 + position2  #оценка качества найденной комбинации

            if score < best_score: #Если сумма позиций меньше текущей лучшей оценки, обновляем
                best_score = score  
                best_result = (a, b, nearest, position1, position2) #сохраняем коэффициенты, список ближайших слов и позиции исходных слов

    if found:

        a, b, nearest, position1, position2 = best_result  #храниться наиболее удачная комбинация из найденных

        print("\nНАЙДЕНА ПОДХОДЯЩАЯ КОМБИНАЦИЯ")

        print(f"Формула: {a} * {word1} + {b} * {word2}")

        print(f"\nПозиция слова {word1}: {position1}")
        print(f"Позиция слова {word2}: {position2}")

        print("\n10 ближайших существительных:")

        for i, (word, similarity) in enumerate(nearest, 1): #последовательный вывод десяти ближайших существительных
            print(f"{i}. {word} — {similarity:.4f}")

    else:
        print("\nПодходящая комбинация не найдена.")

if __name__ == "__main__":
    main()